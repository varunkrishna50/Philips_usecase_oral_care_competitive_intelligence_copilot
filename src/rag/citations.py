"""Structured segments (3B.5), citation validation (3B.6), and source
rendering (3B.7).

Segment/citation_ids is the ONE internal shape produced by both the LLM
path (after parsing its JSON) and the deterministic no-key fallback, so
validation and rendering run identically regardless of which produced
them. The LLM never emits [S1]/[S2] markers itself -- those are
assigned here, after validation, in order of first appearance.
"""
from __future__ import annotations

import re
from decimal import Decimal
from dataclasses import dataclass, field
from typing import Optional

from .comparison_engine import ComparisonRow
from .models import ProductRecord, RetrievalDocument
from .query_understanding import detect_products

# A figure as a whole token: 700, 5, 62,000 (thousands comma), 3.5. Compared as numbers, never as
# substrings, so "5" is not supported by "15x" and "62000" matches "62,000".
_NUMBER_RE = re.compile(r"\d+(?:,\d{3})*(?:\.\d+)?")

QUOTE_MAX_CHARS = 240


def _figures(text: str) -> set[str]:
    """Whole-number tokens in canonical numeric form: "62,000" -> "62000", "$20.00" == "$20" -> "20"."""
    out = set()
    for m in _NUMBER_RE.findall(text):
        value = Decimal(m.replace(",", ""))
        out.add(format(value.normalize(), "f") if value == value.to_integral() else str(value.normalize()))
    return out


@dataclass
class Segment:
    text: str
    citation_ids: list[str]  # evidence_ids
    # True for text WE generated deterministically (status_aware_statement,
    # comparison_engine summaries): the phrasing is correct by
    # construction (exact arithmetic, exact status templates), and a
    # computed number (e.g. a difference) or a "not mentioned" disclosure
    # legitimately isn't a verbatim quote of any single evidence_text --
    # so these skip the hallucination-focused checks below. False (the
    # default) is for LLM-authored text, which DOES need every check.
    trusted: bool = False


@dataclass
class ValidatedSegment:
    text: str
    citation_ids: list[str]  # only ids that passed validation; empty if invalid
    valid: bool
    reasons: list[str] = field(default_factory=list)
    # Carried over from the originating Segment so downstream consumers
    # (the 3C.1 evaluation harness) can tell which segments skipped
    # hallucination-focused validation by construction, rather than by
    # passing it -- offline citation-validity numbers are otherwise
    # inflated by every trusted segment counting as "valid" for free.
    trusted: bool = False


def _mentioned_product_ids(text: str, product_corpus: list[ProductRecord]) -> set[str]:
    """Reuses 3a's own product-recognition logic against the segment's
    OWN text (not the original query) -- if the text clearly names one
    specific real product, the cited evidence had better belong to it.
    Ambiguous/no-match text isn't held to this check (too uncertain to
    be a reliable signal either way)."""
    match = detect_products(text, product_corpus)
    if match.kind == "matched":
        return {match.candidates[0].product_id}
    return set()


def validate_segment(
    segment: Segment,
    evidence_by_id: dict[str, RetrievalDocument],
    product_corpus: list[ProductRecord],
    allowed_product_ids: Optional[set[str]] = None,
    allowed_attributes: Optional[list[str]] = None,
) -> ValidatedSegment:
    """The 3B.6 checks, in order:
    1. every citation id exists
    2. the cited evidence belongs to an expected product (if the query
       scoped the answer to specific product(s))
    3. the cited evidence supports an expected attribute (if scoped)
    4. any product named IN THE SEGMENT TEXT matches the cited product
    5. every numeric value appearing in the text is backed verbatim by
       at least one cited evidence_text (deterministic comparison
       numbers are themselves sourced from evidence_text by
       comparison_engine.py, so this also covers computed differences)
    """
    if segment.trusted:
        # Deterministically generated by our own code (status templates,
        # comparison arithmetic) -- correct by construction, not an LLM
        # claim to police. Still carries whatever real citation_ids it
        # has (possibly none, e.g. a not_mentioned disclosure).
        return ValidatedSegment(text=segment.text, citation_ids=list(segment.citation_ids), valid=True, reasons=[], trusted=True)

    reasons: list[str] = []

    if not segment.citation_ids:
        return ValidatedSegment(text=segment.text, citation_ids=[], valid=False, reasons=["segment has no citations"], trusted=False)

    resolved: list[RetrievalDocument] = []
    for cid in segment.citation_ids:
        ev = evidence_by_id.get(cid)
        if ev is None:
            reasons.append(f"unknown citation id {cid!r}")
            continue
        resolved.append(ev)
    if not resolved:
        return ValidatedSegment(text=segment.text, citation_ids=[], valid=False, reasons=reasons, trusted=False)

    if allowed_product_ids is not None:
        for ev in resolved:
            if ev.product_id not in allowed_product_ids:
                reasons.append(f"citation {ev.evidence_id} belongs to {ev.product_id!r}, not an expected product")

    if allowed_attributes:
        for ev in resolved:
            if ev.attribute not in allowed_attributes:
                reasons.append(f"citation {ev.evidence_id} has attribute {ev.attribute!r}, not in requested {allowed_attributes}")

    mentioned = _mentioned_product_ids(segment.text, product_corpus)
    cited_product_ids = {ev.product_id for ev in resolved}
    if mentioned and not (mentioned & cited_product_ids):
        reasons.append(
            f"segment text names product(s) {sorted(mentioned)} but cites evidence for {sorted(cited_product_ids)}"
        )

    # Numbers that belong to a cited product's OWN name ("Sonicare
    # 4100", "iO Series 10") are never treated as numeric claims needing
    # their own evidentiary backing -- restating the name (even
    # abbreviated, e.g. an LLM dropping a trailing "Rechargeable
    # Toothbrush") is not a separate fact (the product-identity check
    # above already covers it). A literal substring removal of the full
    # name would miss this; matching by digit-token is robust to any
    # paraphrase of the name itself.
    cited_product_name_numbers = set().union(*[_figures(ev.product_name) for ev in resolved])
    evidence_figures = [_figures(ev.evidence_text) | _figures(ev.shown_text) for ev in resolved]
    for number in sorted(_figures(segment.text)):
        if number in cited_product_name_numbers:
            continue
        if not any(number in figures for figures in evidence_figures):
            reasons.append(f"numeric claim {number!r} in segment text is not supported by any cited evidence")

    if reasons:
        return ValidatedSegment(text=segment.text, citation_ids=[], valid=False, reasons=reasons, trusted=False)
    return ValidatedSegment(text=segment.text, citation_ids=[ev.evidence_id for ev in resolved], valid=True, reasons=[], trusted=False)


def validate_segments(
    segments: list[Segment],
    evidence_by_id: dict[str, RetrievalDocument],
    product_corpus: list[ProductRecord],
    allowed_product_ids: Optional[set[str]] = None,
    allowed_attributes: Optional[list[str]] = None,
) -> list[ValidatedSegment]:
    return [
        validate_segment(seg, evidence_by_id, product_corpus, allowed_product_ids, allowed_attributes)
        for seg in segments
    ]


def _quote_key(doc: RetrievalDocument) -> tuple[str, str]:
    text = doc.shown_text.translate({0x2018: "'", 0x2019: "'", 0x201C: '"', 0x201D: '"', 0x2011: "-", 0x2013: "-", 0x2014: "-", 0xA0: " "})
    return (doc.product_id, re.sub(r"[^a-z0-9]+", " ", text.lower()).strip())


def assign_markers(
    validated_segments: list[ValidatedSegment],
    evidence_by_id: Optional[dict[str, RetrievalDocument]] = None,
) -> dict[str, str]:
    """evidence_id -> "S1"/"S2"/... in order of first appearance across
    VALID segments only -- an invalid (rejected) segment contributes no
    citation markers at all.

    With ``evidence_by_id``, markers are numbered per distinct (product, quote): two records that hold
    the same sentence share one marker, so the Sources list shows the quote once."""
    marker_by_id: dict[str, str] = {}
    marker_by_key: dict[tuple[str, str], str] = {}
    for seg in validated_segments:
        if not seg.valid:
            continue
        for cid in seg.citation_ids:
            if cid in marker_by_id:
                continue
            doc = (evidence_by_id or {}).get(cid)
            key = _quote_key(doc) if doc is not None else None
            if key is not None and key in marker_by_key:
                marker_by_id[cid] = marker_by_key[key]
                continue
            marker = f"S{len({m for m in marker_by_id.values()}) + 1}"
            marker_by_id[cid] = marker
            if key is not None:
                marker_by_key[key] = marker
    return marker_by_id


def render_answer_text(validated_segments: list[ValidatedSegment], marker_by_id: dict[str, str]) -> str:
    lines = []
    for seg in validated_segments:
        if not seg.valid:
            continue
        markers = " ".join(f"[{m}]" for m in dict.fromkeys(marker_by_id[cid] for cid in seg.citation_ids))
        lines.append(f"{seg.text} {markers}".strip())
    return "\n\n".join(lines)


def render_comparison_table(rows: list[ComparisonRow], product_a_name: str, product_b_name: str, marker_by_id: dict[str, str]) -> str:
    """One markdown table row per comparison attribute, each cell's
    marker(s) looked up from the SAME marker_by_id a comparison's
    summary paragraph also uses (assign_markers, called once over both
    -- see _answer_comparison in generation.py) -- so table and summary
    share consistent [S1]/[S2] numbering, and render_sources_section
    (unmodified) covers both automatically."""
    def cell(text: str, citation_ids: list[str]) -> str:
        markers = " ".join(f"[{marker_by_id[cid]}]" for cid in dict.fromkeys(citation_ids) if cid in marker_by_id)
        return f"{text} {markers}".strip()

    lines = [
        f"| Feature | {product_a_name} | {product_b_name} |",
        "|---|---|---|",
    ]
    for row in rows:
        lines.append(f"| {row.attribute_label} | {cell(row.cell_a_text, row.cell_a_citation_ids)} | {cell(row.cell_b_text, row.cell_b_citation_ids)} |")
    return "\n".join(lines)


def display_section(ev: RetrievalDocument) -> str:
    """The page section to show next to a quote ("" when there is no meaningful one)."""
    section = ev.source_section
    if section and section != "structured_data":
        return section
    region = ev.source_region or ""
    if region.startswith("spec:"):
        return f"Technical specifications > {region[5:]}"
    if region in ("feature_panels",):
        return "Feature panels"
    if region in ("", "structured_data", "visible_text", "rendered_text", "json_ld", "meta_price", "embedded_price"):
        return ""
    return region


@dataclass
class SourceEntry:
    """One Sources-panel entry: the same data render_sources_section()
    formats into markdown, exposed structured so a presentation layer
    (e.g. app.py's side panel) can render its own cards instead of
    parsing that markdown back apart."""
    marker: str
    product_name: str
    section: str  # "" when there is no meaningful section to show
    quote: str
    url: str


def source_entries(marker_by_id: dict[str, str], evidence_by_id: dict[str, RetrievalDocument]) -> list[SourceEntry]:
    """One entry per distinct marker, in marker order (S1, S2, ...) --
    the single source of truth both render_sources_section() and any
    structured consumer build from."""
    if not marker_by_id:
        return []
    first_by_marker: dict[str, str] = {}
    for evidence_id, marker in marker_by_id.items():
        first_by_marker.setdefault(marker, evidence_id)  # one entry per marker (records sharing a quote share it)
    ordered = sorted(((eid, m) for m, eid in first_by_marker.items()), key=lambda kv: int(kv[1][1:]))
    entries = []
    for evidence_id, marker in ordered:
        ev = evidence_by_id[evidence_id]
        quote = " ".join(ev.shown_text.split())
        if len(quote) > QUOTE_MAX_CHARS:
            quote = quote[:QUOTE_MAX_CHARS].rsplit(" ", 1)[0] + " ..."
        entries.append(SourceEntry(
            marker=marker, product_name=ev.product_name, section=display_section(ev),
            quote=quote, url=ev.source_url,
        ))
    return entries


def render_sources_section(marker_by_id: dict[str, str], evidence_by_id: dict[str, RetrievalDocument]) -> str:
    entries = source_entries(marker_by_id, evidence_by_id)
    if not entries:
        return ""
    lines = ["Sources", ""]
    # Two trailing spaces keep each line on its own line in Markdown renderers (Streamlit).
    br = "  "
    for e in entries:
        lines.append(f"[{e.marker}] {e.product_name} -- official product page{br}")
        if e.section:
            lines.append(f"Section: {e.section}{br}")
        lines.append(f'Quote: "{e.quote}"{br}')
        lines.append(e.url)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
